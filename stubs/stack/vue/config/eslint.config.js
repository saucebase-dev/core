import prettier from 'eslint-config-prettier/flat';
import vue from 'eslint-plugin-vue';
import vueA11y from 'eslint-plugin-vuejs-accessibility';

import {
    configureVueProject,
    defineConfigWithVueTs,
    vueTsConfigs,
} from '@vue/eslint-config-typescript';

// The .vue scan only feeds type-aware rules, which aren't enabled. Scanning the
// whole project follows core's testbench vendor symlink into a loop in a checkout.
configureVueProject({ rootDir: `${import.meta.dirname}/resources` });

const generated = ['**/components/ui/!(saucebase)/**'];

export default defineConfigWithVueTs(
    vue.configs['flat/essential'],
    vueTsConfigs.recommended,
    {
        languageOptions: {
            parserOptions: {
                tsconfigRootDir: import.meta.dirname,
            },
        },
    },
    {
        ignores: [
            'node_modules',
            'public',
            'bootstrap/ssr',
            'stubs',
            'tailwind.config.js',
            'resources/js/components/ui/*',
            'modules/*/resources/js/components/ui/*',
            // A module checked out with both stacks: the React one is linted by the React config.
            'modules/*/resources/js/react',
        ],
    },
    // shadcn-vue components are generated by its CLI, so their findings are not ours to fix.
    ...vueA11y.configs['flat/recommended'].map((config) => ({
        ...config,
        ignores: generated,
    })),
    {
        ignores: generated,
        rules: {
            'vuejs-accessibility/label-has-for': [
                'error',
                { required: { some: ['nesting', 'id'] } },
            ],
            'vuejs-accessibility/anchor-has-content': [
                'error',
                { accessibleChildren: ['NavLinkContent'] },
            ],
            // Reads Inertia's <Link> as the HTML <link> element, which takes no ARIA.
            'vuejs-accessibility/aria-unsupported-elements': 'off',
        },
    },
    {
        rules: {
            'vue/multi-word-component-names': 'off',
            '@typescript-eslint/no-explicit-any': 'off',
        },
    },
    prettier,
);
